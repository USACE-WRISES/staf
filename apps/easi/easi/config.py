@functools.lru_cache(maxsize=None)
def _load(name: str):
    return json.loads((DATA_DIR / name).read_text(encoding="utf-8"))


def cwa_mapping() -> dict[str, dict[str, str]]:
    """function id -> {physical, chemical, biological} contribution codes."""
    rows = _load("cwa-mapping.json")
    return {r["id"]: {k: r[k] for k in OUTCOMES} for r in rows}


def functions() -> list[dict]:
    return _load("functions.json")


def easi_metrics() -> dict:
    return _load("easi-metrics.json")


def metrics_by_id() -> dict[str, dict]:
    return {m["metricId"]: m for m in easi_metrics()["metrics"]}


def screening_methods() -> dict:
    """The canonical automated screening-method catalog.

    ``data/screening-methods.json`` is the single source of truth for the automated
    formulas, exact Good/Fair/Poor boundaries, source hierarchy, and method provenance.
    :mod:`easi.screening_methods` evaluates it and :mod:`easi.methods` renders it, so the
    displayed criteria cannot drift from what actually produced the rating.
    """
    return _load("screening-methods.json")


def criteria_bands(mid: str, indicator: str | None = None) -> dict:
    """Good/Fair/Poor criteria strings for a metric, indicator-aware.

    Automated criteria come from the screening-method catalog so the displayed
    breakpoints are generated by the same band objects the evaluator used. ``indicator``
    selects one input of a worst-of method (e.g. the land-cover metric's ``impervious``
    vs ``agriculture``). Falls back to the generic STAF field prose in
    ``easi-metrics.json`` for anything the catalog does not describe numerically.
    """
    from . import screening_methods as sm

    try:
        method = sm.method_for(mid)
    except KeyError:
        method = None
    if method is not None:
        auto = sm.criteria_for(method).get("automated") or []
        if auto:
            block = next((a for a in auto if a["input"] == indicator), auto[0])
            bands = block.get("bands") or {}
            if bands:
                return {r: bands[r] for r in RATINGS if bands.get(r)}
    return metrics_by_id().get(mid, {}).get("criteria") or {}


