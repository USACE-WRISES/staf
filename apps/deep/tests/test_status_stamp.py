"""Every calculator DEEP ships states its version's status (owner, 2026-10-14), and only that one.

The workbooks are generated by StreamCurves (a banner on each visible sheet, a print header, the
Metadata row) and copied here by the bake, which records each one's status in index.json. DEEP
hands a workbook out only when that status equals the one the version is shown with, and the
website's raw downloads (<id>.xlsx) are the default versions' copies. This reads the repo's own
data: a bake from unstamped workbooks, or a stamp that disagrees with the registry, fails here
instead of silently offering no calculator (tests/test_scenarios.py skips without one).
"""
from __future__ import annotations

import json
import zipfile
from pathlib import Path

import pytest

from deep import session

APP = Path(__file__).resolve().parents[1]
WWW = APP / "www" / "calculators"
REGISTRY = APP / "data" / "deep-assessments.json"


def _index() -> dict:
    path = WWW / "index.json"
    if not path.is_file():
        pytest.skip("no calculators are baked in this checkout")
    return json.loads(path.read_text(encoding="utf-8"))


def _lifecycles() -> dict:
    doc = json.loads(REGISTRY.read_text(encoding="utf-8"))
    return dict((r["assessmentRef"], r["lifecycle"]) for r in doc["assessments"]
                if r.get("assessmentRef"))


def _strings(path: Path) -> str:
    """Every sheet's text (the generator writes inline strings) and any shared strings."""
    with zipfile.ZipFile(path) as z:
        return " ".join(z.read(n).decode("utf-8") for n in z.namelist()
                        if n.startswith("xl/worksheets/sheet") or n == "xl/sharedStrings.xml")


def _stated(text: str) -> list:
    return [s for s in session.LIFECYCLES if session.status_line(s) in text]


def test_the_index_records_a_status_for_every_workbook_and_it_is_the_versions():
    index = _index()
    assert index["schemaVersion"] == 2
    life = _lifecycles()
    assert index["calculators"], "no calculator is baked"
    for ref, rec in index["calculators"].items():
        assert rec.get("status") == life[ref], ref


def test_each_workbook_states_its_status_and_no_other():
    index = _index()
    for ref, rec in index["calculators"].items():
        assert _stated(_strings(WWW / rec["file"])) == [rec["status"]], ref


def test_the_websites_copies_state_their_default_versions_status():
    index = _index()
    doc = json.loads(REGISTRY.read_text(encoding="utf-8"))
    defaults = dict((aid, p.get("defaultVersion")) for aid, p in doc["libraryCatalog"].items())
    life = _lifecycles()
    for aid, name in index["default"].items():
        ref = f"{aid}@v{defaults[aid]}"
        assert (WWW / name).read_bytes() == (WWW / index["calculators"][ref]["file"]).read_bytes()
        assert _stated(_strings(WWW / name)) == [life[ref]], aid
